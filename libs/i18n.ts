const messages: Record<Lang, { [K in MessageKey]: string }> = { en, ja };

export function isLang(value: string | null): value is Lang {
  return value === 'en' || value === 'ja';
}

export function t(
  lang: Lang,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const template = messages[lang][key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}

const BASIN_MESSAGE_KEYS = {
  n_atlantic: 'basinNAtlantic',
  e_pacific: 'basinEPacific',
  w_pacific: 'basinWPacific',
  n_indian: 'basinNIndian',
  s_indian: 'basinSIndian',
  s_pacific: 'basinSPacific',
} as const satisfies Record<string, MessageKey>;

export function basinLabel(lang: Lang, id: string): string {
  const key = BASIN_MESSAGE_KEYS[id as keyof typeof BASIN_MESSAGE_KEYS];
  return key ? t(lang, key) : id;
}

export function displayStormName(name: string, lang: Lang): string {
  return name === 'Unnamed' ? t(lang, 'unnamed') : name;
}
